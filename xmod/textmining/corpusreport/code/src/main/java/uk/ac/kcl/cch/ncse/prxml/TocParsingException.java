package uk.ac.kcl.cch.ncse.prxml;

public class TocParsingException extends Exception {

	private static final long serialVersionUID = 1L;

	public TocParsingException() {
	}

	public TocParsingException(String arg0) {
		super(arg0);
	}

	public TocParsingException(Throwable arg0) {
		super(arg0);
	}

	public TocParsingException(String arg0, Throwable arg1) {
		super(arg0, arg1);
	}

}
